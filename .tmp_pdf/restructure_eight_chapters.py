def count_text(text):
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    text = re.sub(r"!\[[^]]*\]\([^)]*\)", "", text)
    return {
        "han": len(re.findall(r"[\u4e00-\u9fff]", text)),
        "latin_number_groups": len(re.findall(r"[A-Za-z0-9]+(?:[.-][A-Za-z0-9]+)*", text)),
    }

